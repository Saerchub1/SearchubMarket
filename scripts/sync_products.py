
import csv
import html
import io
import re
import shutil
import urllib.request
from pathlib import Path
from urllib.parse import urlparse

SHEET_URL = (
    "https://docs.google.com/spreadsheets/d/"
    "1-6jrw_LldbRtPDZdXQpXfifvxFYijM6n4-17f8z72fM/"
    "gviz/tq?tqx=out:csv&headers=1"
)

PRODUCTS_DIR = Path("products")
MARKER = ".searchub-generated"

def safe_url(value):
    try:
        parsed = urlparse((value or "").strip())
        if parsed.scheme in ("https", "http") and parsed.netloc:
            return parsed.geturl()
    except ValueError:
        pass
    return ""


def slugify(value):
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower())
    return slug.strip("-") or "product"


def escape(value):
    return html.escape(str(value or ""), quote=True)


def generate_html(product):
    name = escape(product["name"])
    price = escape(product["price"])
    image = escape(product["image"])
    link = escape(product["link"])

    image_html = (
        f'<img src="{image}" alt="{name}" loading="lazy">'
        if image else "<p>Image unavailable</p>"
    )

    price_html = (
        f'<p class="price">{price}</p>'
        if price else ""
    )

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="{name} - Searchub by BradDesigning">
<title>{name} | Searchub</title>
<style>
* {{ box-sizing: border-box; }}
body {{
  font-family: Inter, system-ui, sans-serif;
  background: #fff8ff;
  color: #171329;
  margin: 0;
  padding: 30px 15px;
}}
main {{
  max-width: 650px;
  margin: 40px auto;
  padding: 30px;
  border-radius: 25px;
  background: white;
  box-shadow: 0 18px 50px rgba(62,31,105,.15);
  text-align: center;
}}
img {{
  width: 100%;
  max-height: 450px;
  object-fit: contain;
  border-radius: 12px;
}}
h1 {{ overflow-wrap: anywhere; }}
.price {{ font-size: 1.5rem; font-weight: 800; }}
a {{ color: #635bff; }}
.buy {{
  display: block;
  padding: 15px;
  margin-top: 20px;
  background: #635bff;
  color: white;
  text-decoration: none;
  border-radius: 10px;
  font-weight: bold;
}}
</style>
</head>
<body>
<main>
<a href="/">← Back to Searchub</a>
{image_html}
<h1>{name}</h1>
{price_html}
<a class="buy" href="{link}" target="_blank"
rel="noopener noreferrer">Buy Now</a>
</main>
</body>
</html>
"""


def main():
    request = urllib.request.Request(
        SHEET_URL,
        headers={"User-Agent": "Searchub-Automation"}
    )

    with urllib.request.urlopen(request, timeout=30) as response:
        content = response.read().decode("utf-8-sig")

    reader = csv.DictReader(io.StringIO(content))

    products = {}
    used_slugs = set()

    for row in reader:
        name = (row.get("Name") or "").strip()
        status = (row.get("Status") or "Listed").strip().lower()

        if not name or status != "listed":
            continue

        link = safe_url(row.get("Link"))
        image = safe_url(row.get("Image"))

        if not link:
            print(f"Skipping {name}: invalid purchase link")
            continue

        slug = slugify(name)

        if slug in used_slugs:
            raise ValueError(f"Duplicate product name/slug: {slug}")

        used_slugs.add(slug)

        products[slug] = {
            "name": name,
            "price": (row.get("Price") or "").strip(),
            "image": image,
            "link": link
        }

    PRODUCTS_DIR.mkdir(parents=True, exist_ok=True)

    # Create or update listed product folders.
    for slug, product in products.items():
        folder = PRODUCTS_DIR / slug
        folder.mkdir(parents=True, exist_ok=True)

        (folder / MARKER).write_text(
            "Generated by Searchub automation",
            encoding="utf-8"
        )

        (folder / "index.html").write_text(
            generate_html(product),
            encoding="utf-8"
        )

        print(f"Created/updated: {slug}")

    # Delete only folders created by this automation.
    for folder in PRODUCTS_DIR.iterdir():
        if not folder.is_dir():
            continue

        marker = folder / MARKER

        if marker.exists() and folder.name not in products:
            shutil.rmtree(folder)
            print(f"Removed unlisted product: {folder.name}")

    print(f"Finished. {len(products)} listed products synchronized.")


if __name__ == "__main__":
    main()
